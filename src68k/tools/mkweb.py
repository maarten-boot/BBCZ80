#!/usr/bin/env python3
"""Make the web version: build/web/bbc68k.html, one self-contained page.

	mkweb.py [-r R68K_DIR] [--test]

The page (web/page.html with web/app.js and web/loader.js) runs r68k
compiled to WebAssembly by Emscripten (emcc on the PATH):
* r68k's tracked sources (R68K_DIR, default ../r68k next to this
  repository; its firmware as built there), with web/r68k-web.patch
  (Duart.cpp: the page's terminal) and web/webmain.cpp in place of main()
  (main.cpp is compiled with its main renamed);
* the boot image of the stand-alone demo (build/demo/bbc68k-demo/
  ROSCODE1.BIN, make demo), embedded.
The keyword table for loading tokenised programs is taken from main.s.
xterm.js (@xterm/xterm XTERM) is downloaded once to build/web/vendor.
Everything is inlined (-sSINGLE_FILE), so the page works offline, also
opened as a file.

--test builds a Node version too (build/web/node) and runs web/test.js:
boot, the asm demo from the menu, and the upstream test programs (tests/)
typed in through loader.js and run, compared with their bascheck
references (test/bas/u_*.ref).  Then, if chromium and the Python
websockets module are there, web/browsertest.py tries the page itself in
headless Chromium (keys, Escape, Load program, the speed setting).
"""

import argparse
import hashlib
import importlib.util
import html
import json
import os
import re
import shutil
import subprocess
import sys
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.dirname(HERE)
TOP = os.path.dirname(SRC)
WEB = os.path.join(SRC, 'web')
WORK = os.path.join(TOP, 'build', 'web')
DEMO = os.path.join(TOP, 'build', 'demo', 'bbc68k-demo')
XTERM = '5.5.0'
VENDOR = {			# file: (path in the npm package, sha256)
    'xterm.js': ('lib/xterm.js', '1f991ac3b4b283ebf96e60ae23a00a52765dd3a2e46fa6fdda9f1aab032f7495'),
    'xterm.css': ('css/xterm.css', 'ba8e6985669488981ccf40c0cefe3aba80722cb6c92de7ad628b0bd717faf2b6'),
    'LICENSE': ('LICENSE', 'b569f629d00f2626a8100df2a1798210535621e42164dfd426a6fe5aac7b0ccd'),
}
CFLAGS = ['-O2', '-fwasm-exceptions', '-sSUPPORT_LONGJMP=wasm']
LDFLAGS = CFLAGS + ['-sMODULARIZE=1', '-sEXPORT_NAME=R68K',
                    '-sALLOW_MEMORY_GROWTH=1', '-sEXIT_RUNTIME=0']


def vendor():
    d = os.path.join(WORK, 'vendor')
    os.makedirs(d, exist_ok=True)
    for name, (path, sha) in VENDOR.items():
        f = os.path.join(d, name)
        if not os.path.exists(f):
            url = 'https://cdn.jsdelivr.net/npm/@xterm/xterm@%s/%s' % (XTERM, path)
            with urllib.request.urlopen(url) as r, open(f, 'wb') as g:
                g.write(r.read())
        if hashlib.sha256(open(f, 'rb').read()).hexdigest() != sha:
            os.remove(f)
            sys.exit('mkweb: %s: wrong checksum (removed; run again)' % name)
    return d


def compile_r68k(r68k):
    """r68k's sources with the patch, compiled to build/web/obj."""
    src = os.path.join(WORK, 'r68k-src')
    if os.path.exists(src):
        shutil.rmtree(src)
    for f in subprocess.run(['git', 'ls-files'], cwd=r68k, check=True,
                            capture_output=True, text=True).stdout.split():
        os.makedirs(os.path.dirname(os.path.join(src, f)), exist_ok=True)
        shutil.copy(os.path.join(r68k, f), os.path.join(src, f))
    subprocess.run(['patch', '-s', '-p1', '-i',
                    os.path.join(WEB, 'r68k-web.patch')], cwd=src, check=True)
    # the opcode handlers are generated by a host program
    subprocess.run(['make', '-C', 'musashi', 'm68kops.c'], cwd=src,
                   check=True, stdout=subprocess.DEVNULL)
    obj = os.path.join(WORK, 'obj')
    if os.path.exists(obj):
        shutil.rmtree(obj)
    os.makedirs(obj)
    cxx = CFLAGS + ['-std=c++20', '-Iinclude', '-I.']
    jobs = [['emcc'] + CFLAGS + ['-c', 'musashi/%s.c' % f]
            for f in ('m68kcpu', 'm68kdasm', 'm68kops')]
    jobs.append(['emcc'] + CFLAGS + ['-c', 'musashi/softfloat/softfloat.c'])
    jobs += [['em++'] + cxx + ['-c', f] for f in (
        'machine/AddressDecoder.cpp', 'machine/Duart.cpp', 'machine/Memory.cpp',
        'rosco_m68k_glue/cpuglue.cpp', 'rosco_m68k_glue/memoryglue.cpp')]
    jobs.append(['em++'] + cxx + ['-Dmain=r68k_native_main', '-c', 'main.cpp'])
    jobs.append(['em++'] + cxx + ['-c', os.path.join(WEB, 'webmain.cpp')])
    procs = []
    for j in jobs:
        o = os.path.join(obj, os.path.splitext(os.path.basename(j[-1]))[0] + '.o')
        procs.append(subprocess.Popen(j + ['-o', o], cwd=src))
    if any(p.wait() for p in procs):
        sys.exit('mkweb: compiling r68k failed')
    return sorted(os.path.join(obj, f) for f in os.listdir(obj))


def link(objs, rom, out, env, single):
    os.makedirs(os.path.dirname(out), exist_ok=True)
    args = ['em++'] + LDFLAGS + objs + ['-o', out, '-sENVIRONMENT=' + env,
            '--embed-file', os.path.join(DEMO, 'ROSCODE1.BIN') + '@/ROSCODE1.BIN',
            '--embed-file', rom + '@/firmware/rosco_m68k.rom']
    if single:
        args.append('-sSINGLE_FILE=1')
    subprocess.run(args, check=True)


def keywords():
    """The bytes of main.s's keyword table (KEYWDS)."""
    out, on = [], False
    for l in open(os.path.join(SRC, 'main.s')):
        if l.startswith('KEYWDS:'):
            on = True
            l = l[len('KEYWDS:'):]
        elif on and re.match(r'^\w', l):
            break
        if not on:
            continue
        l = l.split('!')[0].strip()
        m = re.match(r'\.data1\s+(.*)', l)
        if m:
            out += [int(v, 0) for v in m.group(1).split(',')]
        m = re.match(r'\.ascii\s+"(.*)"', l)
        if m:
            out += list(m.group(1).encode())
    return out


def text(f):
    """A text file in UTF-8 or else Latin-1 (r68k's licence)."""
    b = open(f, 'rb').read()
    try:
        return b.decode()
    except UnicodeDecodeError:
        return b.decode('latin-1')


def licences(r68k, vend):
    musashi = text(os.path.join(r68k, 'musashi', 'readme.txt'))
    musashi = musashi[musashi.index('LICENSE AND COPYRIGHT'):].split('\n\n\n')[0]
    minix = os.path.join(os.path.dirname(TOP), 'minix-st-2.0.4', 'src', 'LICENSE')
    parts = [('BBC BASIC (R.T. Russell)', text(os.path.join(TOP, 'licence.txt'))),
             ('r68k and the rosco_m68k firmware', text(os.path.join(r68k, 'LICENSE.md'))),
             ('Musashi', musashi),
             ('Minix 2.0.4', text(minix)),
             ('xterm.js', text(os.path.join(vend, 'LICENSE')))]
    return ''.join('<h3>%s</h3><pre>%s</pre>' % (html.escape(t), html.escape(x))
                   for t, x in parts)


def script(text):
    """Text for inside <script>: no closing tag in it."""
    return text.replace('</script', '<\\/script')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('-r', default=os.path.join(os.path.dirname(TOP), 'r68k'))
    ap.add_argument('--test', action='store_true')
    a = ap.parse_args()
    r68k = os.path.abspath(a.r)
    rom = os.path.join(r68k, 'firmware', 'rosco_m68k.rom')
    if not os.path.exists(os.path.join(DEMO, 'ROSCODE1.BIN')):
        sys.exit('mkweb: no %s (make demo first)' % os.path.join(DEMO, 'ROSCODE1.BIN'))
    vend = vendor()
    objs = compile_r68k(r68k)
    js = os.path.join(WORK, 'page', 'r68k.js')
    link(objs, rom, js, 'web', True)
    parts = {
        'XTERM_CSS': open(os.path.join(vend, 'xterm.css')).read(),
        'XTERM_JS': script(open(os.path.join(vend, 'xterm.js')).read()),
        'R68K_JS': script(open(js).read()),
        'LOADER_JS': script(open(os.path.join(WEB, 'loader.js')).read()),
        'TOKENS': json.dumps(keywords()),
        'APP_JS': script(open(os.path.join(WEB, 'app.js')).read()),
        'LICENCES': licences(r68k, vend),
    }
    page = re.sub(r'@@(\w+)@@', lambda m: parts[m.group(1)],
                  open(os.path.join(WEB, 'page.html')).read())
    out = os.path.join(WORK, 'bbc68k.html')
    with open(out, 'w') as f:
        f.write(page)
    print('%s: %d bytes' % (out, os.path.getsize(out)))
    if a.test:
        node = os.path.join(WORK, 'node', 'r68k.js')
        link(objs, rom, node, 'node', False)
        with open(os.path.join(WORK, 'node', 'tokens.json'), 'w') as f:
            json.dump(keywords(), f)
        if subprocess.run(['node', os.path.join(WEB, 'test.js'), node,
                           os.path.join(WORK, 'node', 'tokens.json'),
                           os.path.join(TOP, 'tests'),
                           os.path.join(SRC, 'test', 'bas')]).returncode:
            return 1
        if shutil.which('chromium') and importlib.util.find_spec('websockets'):
            return subprocess.run([sys.executable, os.path.join(WEB, 'browsertest.py'),
                                   out, os.path.join(TOP, 'tests')]).returncode
        print('mkweb: no chromium or websockets module: page not tried in a browser')
    return 0


if __name__ == '__main__':
    sys.exit(main())
